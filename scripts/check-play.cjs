// Checks technical release configuration only; Play approval/privacy review is separate.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const {execFileSync} = require('node:child_process');
const read = file => fs.readFileSync(file,'utf8');
const config = JSON.parse(read('capacitor.config.json'));
assert.equal(config.appId,'com.kalvimurasu.nmms');
assert.equal(config.appName,'NMMS Spark');
assert.equal(config.android.allowMixedContent,false);
assert.equal(config.android.webContentsDebuggingEnabled,false);
const manifest=read('android/app/src/main/AndroidManifest.xml');
assert(manifest.includes('android:allowBackup="false"'));
assert(manifest.includes('android:usesCleartextTraffic="false"'));
assert(manifest.includes('android:dataExtractionRules="@xml/data_extraction_rules"'));
assert(manifest.includes('android:icon="@mipmap/ic_launcher"'));
assert.deepEqual([...manifest.matchAll(/<uses-permission\s+android:name="([^"]+)"/g)].map(m=>m[1]),['android.permission.INTERNET']);
const gradle=read('android/app/build.gradle');
assert(gradle.includes('debuggable false'));
assert(gradle.includes("task.dependsOn('validatePlaySigning')"));
assert(gradle.includes('NMMS_UPLOAD_STORE_PASSWORD'));
assert(Number(gradle.match(/versionCode\s+(\d+)/)[1])>=4);
assert(Number(read('android/variables.gradle').match(/targetSdkVersion\s*=\s*(\d+)/)[1])>=36);
const secrets=execFileSync('git',['ls-files','*.jks','*.keystore','*.p12','*keystore.properties'],{encoding:'utf8'}).trim();
assert.equal(secrets,'','Signing material must not be tracked');
const icon=fs.readFileSync('release/play-store-icon-512.png');
assert.equal(icon.readUInt32BE(16),512);
assert.equal(icon.readUInt32BE(20),512);
for(const file of ['app.js','style.css','index.html']) assert.equal(read('www/'+file),read('android/app/src/main/assets/public/'+file),'Run npm run sync:android before release checks');
console.log('PASS: API 36, release signing guard, app identity/icons, HTTPS-only configuration, backup exclusions, minimal permissions, native asset sync');
console.log('Privacy/contact/audience approval, signed AAB generation and real-device testing are still required; this check does not certify Play eligibility.');
